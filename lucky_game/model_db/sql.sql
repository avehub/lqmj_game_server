  `created` bigint DEFAULT '0' COMMENT '创建时间',
  `id` int NOT NULL AUTO_INCREMENT COMMENT '房间ID',
  `club_id` int NOT NULL DEFAULT '0' COMMENT '茶馆ID,无茶馆为0',
  `creator` int DEFAULT NULL COMMENT '房主ID(玩家ID)',
