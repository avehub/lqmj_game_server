  `status` smallint NOT NULL DEFAULT '0' COMMENT '房间状态',
  `updated` bigint DEFAULT '0' COMMENT '更新时间',
  `play_type` smallint NOT NULL DEFAULT '1' COMMENT '玩法类型',
  `cs_type` int NOT NULL DEFAULT '0' COMMENT '子服务类型',
